package envtemplate

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/YewFence/stacklint/internal/wiring"
)

// CIOutput returns the CI artifact path for a combination: .env.ci for the
// base, .env.ci.<variant> for variants.
func CIOutput(target Target) string {
	name := ".env.ci"
	if target.Variant != "base" {
		name += "." + target.Variant
	}
	return filepath.Join(target.Stack.Dir, name)
}

// CIArtifact builds the .env.ci artifact for a combination: every
// @env-example value in its include graph, deterministically serialized.
// The artifact exists for compose-CLI consumers that need a materialized
// dotenv file; stacklint itself never reads it, and consumers decide whether
// to commit it. The result's target output is the CI artifact path.
func CIArtifact(target Target) (*Result, error) {
	output := CIOutput(target)
	if output == target.Output {
		return nil, fmt.Errorf("CI artifact %s collides with the template output", filepath.Base(output))
	}
	examples, err := wiring.ExampleValues(target.Files, target.Stack.Dir)
	if err != nil {
		return nil, err
	}
	lines := []string{"## Generated by stacklint from @env-example markers; do not edit."}
	for _, name := range sortedNames(examples) {
		assignment, err := encodeAssignment(name, examples[name])
		if err != nil {
			return nil, err
		}
		lines = append(lines, assignment)
	}
	ciTarget := target
	ciTarget.Output = output
	return &Result{Target: ciTarget, Content: []byte(strings.Join(lines, "\n") + "\n")}, nil
}
