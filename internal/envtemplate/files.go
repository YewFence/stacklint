package envtemplate

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/YewFence/stacklint/internal/config"
)

// ReadOutput validates the target and reads an existing template without following symlinks.
// A missing template returns nil bytes and no error.
func ReadOutput(target Target) ([]byte, error) {
	dir, err := filepath.EvalSymlinks(target.Stack.Dir)
	if err != nil {
		return nil, err
	}
	if dir != filepath.Clean(target.Stack.Dir) {
		return nil, fmt.Errorf("refusing symlink stack directory %s", target.Stack.RelPath)
	}
	info, err := os.Lstat(target.Output)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("refusing non-regular or symlink output %s", filepath.Base(target.Output))
	}
	return os.ReadFile(target.Output)
}

// Write atomically replaces a previously prepared template.
func Write(result *Result) error {
	if _, err := ReadOutput(result.Target); err != nil {
		return err
	}
	file, err := os.CreateTemp(result.Target.Stack.Dir, ".stacklint-env-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(file.Name()) }()
	if _, err := file.Write(result.Content); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Chmod(0o644); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), result.Target.Output)
}

// Generated reports whether bytes carry a known generated-template header.
func Generated(data []byte) bool {
	first, _, _ := bytes.Cut(data, []byte("\n"))
	trimmed := strings.TrimLeft(string(first), "# ")
	return strings.HasPrefix(trimmed, "Generated by stacklint;") || strings.HasPrefix(trimmed, "Generated from compose.yaml by compose-env;")
}

// EnvFilePassthrough tests the precondition of an env-file-passthrough exemption.
func EnvFilePassthrough(ctx context.Context, cfg *config.Config, root string, target Target, excluded []string) (bool, []string, error) {
	graph, err := newGraph(cfg, root, target, excluded)
	if err != nil {
		return false, nil, err
	}
	model, err := graph.load(ctx)
	if err != nil {
		return false, uniqueStrings(graph.warnings), err
	}
	scan := &scanner{graph: graph, originals: map[string]bool{}, effectiveExpressions: map[string]bool{}, effectivePass: map[string]bool{}}
	scan.collectEffective(model, nil)
	return scan.passthrough, uniqueStrings(graph.warnings), nil
}
